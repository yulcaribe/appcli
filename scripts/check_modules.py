#!/usr/bin/env python3
"""Static checks for H298A APCLI build candidates. Never loads a kernel module."""
from pathlib import Path
import shutil
import subprocess
import sys

EXPECTED_MAGIC = "2.6.36 SMP mod_unload MIPS32_R2 32BIT MT_SMTC"
MODULES = ("mt7603eap.ko", "mt7612e_ap.ko")

def stock_abi_allocator_check(path: Path) -> bool:
    """Compare the known-crashing allocation path against H298A stock binaries.

    The actual ZTE 5GHz stock driver RtmpOsStatsAlloc calls os_alloc_mem
    and allocates 0x70 bytes for struct net_device_stats.
    The generic MT7510 build generated by GCC 10 inlines kmalloc_caches
    and allocated only 0x5c bytes. It kernel-oopsed on H298A.
    This check rejects that KNOWN BAD signature only; PASS is not ABI proof.
    """
    objdump = shutil.which("mips-linux-gnu-objdump") or shutil.which("llvm-objdump")
    if not objdump:
        print("BLOCKED: no MIPS disassembler available")
        return False
    args = [objdump, "-dr"]
    if "llvm-objdump" in objdump:
        args += ["--disassemble-symbols=RtmpOsStatsAlloc", str(path)]
    else:
        args += ["--disassemble=RtmpOsStatsAlloc", str(path)]
    process = subprocess.run(args, capture_output=True, text=True, check=False)
    assembly = process.stdout
    if process.returncode or "<RtmpOsStatsAlloc>:" not in assembly:
        print("BLOCKED: cannot disassemble RtmpOsStatsAlloc", process.stderr[:300])
        return False
    direct_slab_alloc = "kmalloc_caches" in assembly and "kmem_cache_alloc" in assembly
    print("KNOWN-CRASH allocator path (kmalloc_caches -> kmem_cache_alloc):", direct_slab_alloc)
    if direct_slab_alloc:
        print("BLOCKED: exact path caused MIPS Oops in kmem_cache_alloc on H298A")
    # Lack of known-bad signature does not prove ZTE ABI compatibility.
    return not direct_slab_alloc


def inspect(path: Path) -> bool:
    print(f"\n=== {path.name} ===")
    if not path.is_file():
        print("NO OUTPUT: compilation did not produce this driver")
        return False
    def cmd(*argv: str) -> str:
        p = subprocess.run(argv, capture_output=True, text=True, check=False)
        if p.returncode:
            print("Error:", " ".join(argv), p.stderr[:300])
        return p.stdout
    elf = cmd("readelf", "-h", str(path))
    modinfo = cmd("readelf", "-p", ".modinfo", str(path))
    symbols = cmd("readelf", "-Ws", str(path))
    big = "big endian" in elf
    mips = "Machine:" in elf and "MIPS" in elf
    vermagic = "vermagic=" + EXPECTED_MAGIC in modinfo
    apcli = any(word in symbols.lower() for word in ("apcli", "ap_client"))
    print("MIPS ELF:", mips)
    print("Big endian:", big)
    print("Exact original ZTE vermagic:", vermagic)
    print("APCLI-related ELF symbols:", apcli)
    print("Firmware ABI / unresolved symbols / AP+STA / WPA2 handshake: NOT TESTED")
    print("DO NOT LOAD OR FLASH without matching H298A kernel ABI and recovery testing.")
    allocator_ok = stock_abi_allocator_check(path)
    return bool(mips and big and vermagic and apcli and allocator_ok)

def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("build-results")
    results = {name: inspect(root / name) for name in MODULES}
    print("\nStatic gate:", "PASS" if all(results.values()) else "FAIL", results)
    print("Static PASS is not real device compatibility or functional validation.")
    return 0 if all(results.values()) else 1

if __name__ == "__main__":
    sys.exit(main())